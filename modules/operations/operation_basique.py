
def addition(valeur1, valeur2):
    resultat = valeur1 + valeur2
    return resultat

def soustraction(valeur1, valeur2):
    resultat = valeur1 - valeur2
    return resultat

def multiplication(valeur1, valeur2):
    resultat = valeur1 * valeur2
    return resultat

def division(valeur1, valeur2):
    resultat = valeur1 / valeur2
    return resultat


